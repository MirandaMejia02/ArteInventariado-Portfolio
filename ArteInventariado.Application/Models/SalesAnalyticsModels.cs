namespace ArteInventariado.Application.Models;

public enum AnalyticsComparisonKind
{
    PreviousEquivalent = 1,
    SamePeriodPreviousYear = 2
}

public enum HistoricalDataQuality
{
    Exact = 1,
    Partial = 2,
    Unavailable = 3
}

/// <summary>
/// Distinguishes the two intentional null-ID subcategory states in historical
/// analytics. A concrete subcategory continues to be selected through its ID.
/// </summary>
public enum AnalyticsSubcategoryFilter
{
    All = 0,
    ExplicitlyUnassigned = 1,
    HistoricalUnavailable = 2
}

public static class AnalyticsSubcategoryFilterOptions
{
    public const string ExplicitlyUnassignedLabel = "Sin subcategoría";
    public const string HistoricalUnavailableLabel = "No disponible (histórico)";

    // Negative IDs are reserved for UI options and can never collide with a
    // persisted SubcategoriaId generated by SQLite.
    public const int ExplicitlyUnassignedOptionId = -1;
    public const int HistoricalUnavailableOptionId = -2;

    public static AnalyticsSubcategoryFilter FromOptionId(int optionId) => optionId switch
    {
        ExplicitlyUnassignedOptionId => AnalyticsSubcategoryFilter.ExplicitlyUnassigned,
        HistoricalUnavailableOptionId => AnalyticsSubcategoryFilter.HistoricalUnavailable,
        _ => AnalyticsSubcategoryFilter.All
    };
}

